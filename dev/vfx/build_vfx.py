#!/usr/bin/env python3
"""Render the pixel VFX recipes (dev/vfx/recipes/*.json) with the scenario-pixel-vfx skill's engine.
Writes the sprite sheets to img/vfx/<name>.png (what the game loads) and their frame data to
dev/ext/04p_pxv_atlas.js. Previews (GIFs, frame folders) stay in a temp dir and are never committed.
Usage (from dev/):  python3 vfx/build_vfx.py [name ...]   (no names = all recipes)
"""
import json, os, re, subprocess, sys, tempfile, glob, shutil
DEV = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(DEV)
RENDER = os.path.join(REPO, '.claude', 'skills', 'scenario-pixel-vfx', 'scripts', 'render.mjs')
RECIPES = os.path.join(DEV, 'vfx', 'recipes'); OUT = os.path.join(REPO, 'img', 'vfx')
os.makedirs(OUT, exist_ok=True)
names = sys.argv[1:] or sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(RECIPES, '*.json')))
tmp = tempfile.mkdtemp()
def render(path, out):
    r = subprocess.run(['node', RENDER, path, '--out', out, '--force'], capture_output=True, text=True)
    if r.returncode: sys.exit(f'{path}: render failed\n{r.stderr or r.stdout}')
for n in names:
    src = os.path.join(RECIPES, n + '.json'); rec = json.load(open(src))
    st = re.sub('[^a-z0-9]+', '-', n.lower()).strip('-')  # the renderer names files from a slug of the name
    render(src, tmp)
    if rec.get('vary'):
        # "vary": one entry per frame, {"seed": s, "layers": {"<index>": {param: value}}}. Frame i is taken from a render of the
        # recipe with entry i applied, so shapes that the engine keeps still (a pinned crescent) can shift and crackle every frame.
        from PIL import Image
        j = json.load(open(os.path.join(tmp, st + '.json'))); sheet = Image.open(os.path.join(tmp, st + '.png')).convert('RGBA')
        for i, v in enumerate(rec['vary'][:len(j['frames'])]):
            rv = json.loads(json.dumps(rec)); rv.pop('vary'); rv['seed'] = v.get('seed', rv.get('seed', 1))
            for li, ov in v.get('layers', {}).items(): rv['layers'][int(li)].update(ov)
            vd = tempfile.mkdtemp(); vp = os.path.join(vd, 'v.json'); json.dump(rv, open(vp, 'w')); render(vp, vd)
            f = j['frames'][i]['frame']; box = (f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h'])
            sheet.paste(Image.open(os.path.join(vd, st + '.png')).convert('RGBA').crop(box), box[:2]); shutil.rmtree(vd)
        sheet.save(os.path.join(tmp, st + '.png'), optimize=True)
    shutil.copy(os.path.join(tmp, st + '.png'), os.path.join(OUT, n + '.png'))
    shutil.copy(os.path.join(tmp, st + '.json'), os.path.join(tmp, n + '.atlas.json'))
# the atlas for every sheet in img/vfx (frame size, count, fps, loop, impact frame, pivot)
atlas = {}
for p in sorted(glob.glob(os.path.join(OUT, '*.png'))):
    n = os.path.basename(p)[:-4]; a = os.path.join(tmp, n + '.atlas.json')
    if not os.path.exists(a):  # not re-rendered this run: keep the entry from the current atlas file
        continue
    j = json.load(open(a)); f0 = j['frames'][0]['frame']; m = j['meta']
    atlas[n] = {'w': f0['w'], 'h': f0['h'], 'n': len(j['frames']), 'cols': m['size']['w'] // f0['w'], 'fps': m['fps'], 'loop': m['loop'], 'impact': m.get('impactFrame', 0), 'pivot': m.get('pivot', [.5, .5])}
af = os.path.join(DEV, 'ext', '04p_pxv_atlas.js')
if os.path.exists(af):  # merge with sheets rendered earlier
    old = open(af).read(); s = old.index('{'); prev = json.loads(old[s:old.rindex('}') + 1])
    prev.update(atlas); atlas = {k: v for k, v in prev.items() if os.path.exists(os.path.join(OUT, k + '.png'))}  # drop sheets whose png was removed
open(af, 'w').write('// Generated by dev/vfx/build_vfx.py from dev/vfx/recipes: pixel VFX sprite sheets in img/vfx (frame size, count, fps, impact frame, pivot).\nconst PXV_ATLAS=' + json.dumps(atlas, separators=(',', ':'), sort_keys=True) + ';\n')
shutil.rmtree(tmp)
print(f'rendered {len(names)} sheets; {len(atlas)} in the atlas; img/vfx = {sum(os.path.getsize(p) for p in glob.glob(os.path.join(OUT, "*.png")))//1024} KB')
